def check():
    """Problems with the data, as a list of strings - should be empty.

    Every entry needs both languages, a known group, and see-also links
    that land somewhere. Not used at runtime.
    """
    ids = {e["id"] for e in ENTRIES} | {l[0] for l in LISTS}
    cats = {c[0] for c in CATEGORIES}
    out = []
    seen = set()
    for e in ENTRIES:
        if e["id"] in seen:
            out.append(f"duplicate id {e['id']}")
        seen.add(e["id"])
        if e["cat"] not in cats:
            out.append(f"{e['id']}: unknown group {e['cat']}")
        for lang in ("en", "ta"):
            if not e[lang]["name"] or not e[lang]["def"]:
                out.append(f"{e['id']}: missing {lang}")
        for s in e["see"]:
            if s not in ids:
                out.append(f"{e['id']}: see-also {s} goes nowhere")
        for w in e["where"]:
            if w not in WHERE:
                out.append(f"{e['id']}: unknown place {w}")
    return out
